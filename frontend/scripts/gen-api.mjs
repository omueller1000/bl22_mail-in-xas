// Regenerate src/api/schema.d.ts from the backend's OpenAPI schema.
// Requires uv (https://docs.astral.sh/uv/); no running backend or database needed.
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const backend = resolve(root, "../backend");
const outFile = resolve(root, "src/api/schema.d.ts");

const json = execFileSync("uv", ["run", "--quiet", "python", "-m", "app.export_openapi"], {
  cwd: backend,
  encoding: "utf8",
});

const ast = await openapiTS(JSON.parse(json));
const header = "// Generated by `npm run gen:api` from the backend's OpenAPI schema. Do not edit.\n\n";
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, header + astToString(ast));
console.log(`Wrote ${outFile}`);
